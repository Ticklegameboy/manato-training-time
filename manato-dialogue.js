window.createManatoSpeech=function(artwork){
 const data=window.MANATO_DIALOGUE,pull=new Set(['normal','suppress','moving']);
 let pending=null,lastRequest=-100,normalTurns=0,hitTurns={},lastReactionBody=null,lastReactionStage=null;
 let floats=[],everHit=false,hasHung=false,resumePending=false,lastBody=null,lastEmit=-100,nextIdle=0,serial=0,lastContact=-100,quietSwitch=false,calmLines=0,lastStage='normal',lastText='',cursors=new Map(),anchor={x:128,y:170};
 const bodyOf=id=>id==='navel'?'navel':id==='abdomen'?'abdomen':id?.includes('armpit')?'armpit':'waist';
 function pick(id,bank){const i=cursors.get(id)||0;cursors.set(id,i+1);let text=bank[i%bank.length];if(text===lastText&&bank.length>1){text=bank[(i+1)%bank.length];cursors.set(id,i+2);}return text;}
 function emit(text,stage,now,body=null,reason='idle'){
  const red=reason==='hit'&&body==='navel',green=reason==='hit'&&body==='armpit';
  const intensity=red?2:green?1:0;
  if(floats.length){
   // Keep the current line intact. Retain one upcoming reaction, never a backlog.
   if(!pending||reason!=='hit'||pending.reason!=='hit'||intensity>=pending.intensity)pending={text,stage,body,reason,intensity};
   lastRequest=now;nextIdle=now+(reason==='hit'?2.1:3.3);return;
  }
  pending=null;
  const kind=data.exertion.includes(text)?'exertion':data.interjections[stage]?.includes(text)?'interjection':'line';
  if(stage==='normal')normalTurns++;
  if(reason==='hit'){hitTurns[stage]=(hitTurns[stage]||0)+1;lastReactionBody=body;lastReactionStage=stage;}
  floats.push({text,stage,body,reason,kind,intensity,color:data.colors[stage]||data.colors.normal,age:0,life:kind!=='line'?1.05:red?1.65:1.55,lane:(serial++%2?1:-1),size:red?12.5:green?11:10.5});
  const local=window.MANATO_I18N;
  if(kind==='line'&&local&&local.language!=='zh-Hant'){
   const readingTime=[...local.translate(text)].length/(local.language==='en'?20:12)+.35;
   floats.at(-1).life=Math.max(floats.at(-1).life,Math.min(3.4,readingTime));
  }
  lastEmit=now;lastText=text;nextIdle=now+(reason==='hit'?2.1:3.3);
 }
 function idle(stage,now,recovery=false){
  let bank,id,body=lastBody;
  if(stage==='normal'){
   const quiet=now-lastContact+1e-9>=5;
   if(!everHit||(!hasHung&&quiet&&calmLines>=2)){bank=data.boast;id='boast';body=null;}
   else {
    const type=hasHung?'recovered':'teased';body=recovery||quiet?'general':(lastBody||'general');
    bank=data[type][body];id=type+'.'+body;
    if(quiet&&!hasHung)calmLines++;
    if(body==='general')body=null;
   }
  }else {
   const quiet=now-lastContact+1e-9>=5;
   body=quiet?'general':(lastBody||'general');bank=data[stage]?.[body]||data[stage]?.general;id=stage+'.'+body;
   // Keep the user's lines intact; quiet chatter avoids even anatomical general lines.
   if(quiet&&bank)bank=bank.filter(text=>!/[腰腋腹肚]|胳肢|肌肉/.test(text));
   if(body==='general')body=null;
  }
  if(stage==='normal'&&!recovery&&(id==='boast'||(id==='recovered.general'&&now-lastContact>=5))&&normalTurns%3!==0){bank=data.exertion;id='exertion';body=null;}
  if(bank)emit(pick(id,bank),stage,now,body,recovery?'recovery':'idle');
 }
 function head(frame){const l=artwork.groups[frame.key]?.geometry[frame.index]?.landmarks;return l?{x:l.navel[0],y:(l.pit+l.pec)/2-87}:anchor;}
 function reset(frame){normalTurns=0;hitTurns={};lastReactionBody=lastReactionStage=null;pending=null;lastRequest=-100;floats=[];everHit=hasHung=resumePending=false;lastBody=null;lastEmit=-100;nextIdle=0;serial=0;lastContact=-100;quietSwitch=false;calmLines=0;lastStage='normal';lastText='';cursors.clear();anchor=head(frame);idle('normal',0);}
 function hit(stage,id,now){
  const renewed=now-lastContact>=1;
  everHit=true;lastContact=now;quietSwitch=false;calmLines=0;const body=bodyOf(id),changed=body!==lastBody,red=body==='navel';lastBody=body;
  const previous=floats.at(-1),interval=red?.55:changed?.36:.8;
  if(now-Math.max(lastEmit,lastRequest)<interval&&previous?.reason==='hit'&&!(red&&previous.intensity<2))return;
  const count=hitTurns[stage]||0,cycle=['hanging','shaking'].includes(stage)?3:2;
  const useShort=!renewed&&body===lastReactionBody&&stage===lastReactionStage&&count%cycle!==0;
  const bank=useShort?data.interjections[stage]:(data[stage]?.[body]||data.suppress[body]);
  emit(pick(useShort?'interjection.'+stage:stage+'.'+body,bank),stage,now,body,'hit');
  lastStage=stage;
 }
 function update(dt,status){
  floats=floats.filter(f=>(f.age+=dt)<f.life);
  const frame=status.visual;
  let target=head(frame);
  if(status.blend){const b=status.blend,a=head(b.from),z=head(b.to),t=Math.min(1,b.time/b.duration),w=t*t*(3-2*t);target={x:a.x+(z.x-a.x)*w,y:a.y+(z.y-a.y)*w};}
  const follow=1-Math.exp(-dt*22);anchor.x+=(target.x-anchor.x)*follow;anchor.y+=(target.y-anchor.y)*follow;
  if(status.state!=='playing'){
   if(!floats.length&&pending){const line=pending;pending=null;emit(line.text,line.stage,status.elapsed,line.body,line.reason);}
   return;
  }
  // Gameplay lastHit also tracks held contact and release, not only damage pulses.
  if(Number.isFinite(status.lastHit))lastContact=Math.max(lastContact,status.lastHit);
  const suspended=!pull.has(frame.key)&&frame.key!=='release';
  if(suspended){hasHung=true;resumePending=true;}
  if(frame.key==='normal'&&resumePending&&status.mode==='normal'){
   resumePending=false;quietSwitch=status.elapsed-lastContact+1e-9>=5;idle('normal',status.elapsed,true);
  }else if(status.mode===frame.key&&everHit&&!quietSwitch&&status.elapsed-lastContact+1e-9>=5){
   quietSwitch=true;pending=null;idle(status.mode,status.elapsed);
  }else if(status.mode===frame.key&&lastStage!==status.mode&&['normal','breathingAngry','breathingExhausted'].includes(status.mode)){
   idle(status.mode,status.elapsed);
  }else if(status.elapsed>=nextIdle&&status.elapsed-lastEmit>1.8){
   // Waiting for the actual pose avoids a calm breath line while still laughing.
   if(status.mode===frame.key)idle(status.mode,status.elapsed);
  }
  if(frame.key===status.mode)lastStage=status.mode;
  if(!floats.length&&pending){const line=pending;pending=null;emit(line.text,line.stage,status.elapsed,line.body,line.reason);}
 }
 function finish(now){pending=null;emit(pick('release',data.release),'release',now,null,'release');}
 function layout(f){
  const age=f.age,fade=Math.min(1,age/.07)*Math.min(1,(f.life-age)/.4),rise=age*19;
  const wobble=f.intensity===2?Math.sin(age*49)*1.5*Math.max(0,1-age/.55):0;
  const size=f.size*(1+(f.intensity===2?.1:.04)*Math.max(0,1-age/.18));
  const local=window.MANATO_I18N,text=local?local.translate(f.text):f.text;
  const lines=local?local.lines(text,size,222):[text];
  const width=Math.max(...lines.map(line=>local?local.width(line,size):[...line].length*size));
  return {text,lines,x:Math.max(8+width/2,Math.min(248-width/2,anchor.x+f.lane*(18+age*7)+wobble)),y:Math.max(18,anchor.y-34-rise-(lines.length-1)*(size+2)),size,alpha:Math.max(0,fade)};

 }
 function draw(ctx){
  ctx.save();ctx.textAlign='center';ctx.textBaseline='middle';ctx.lineJoin='round';
  for(const f of floats){const p=layout(f);ctx.font=`800 ${p.size}px "Microsoft JhengHei", "PingFang TC", sans-serif`;ctx.globalAlpha=p.alpha;ctx.lineWidth=2.8;ctx.strokeStyle='#271c35';ctx.fillStyle=f.color;p.lines.forEach((line,j)=>{ctx.strokeText(line,p.x,p.y+j*(p.size+2));ctx.fillText(line,p.x,p.y+j*(p.size+2));});}
  ctx.restore();
 }
 return {reset,hit,update,finish,draw,snapshot:()=>({everHit,hasHung,resumePending,lastBody,lastContact,calmLines,quietSwitch,pending:pending?{...pending}:null,anchor:{...anchor},floats:floats.map(f=>({...f,...layout(f),sourceText:f.text}))})};
};
